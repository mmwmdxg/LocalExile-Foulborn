"""Generate src/GameServer.Gateway/Item/FoulbornMap.cs from poedb's Foulborn page.

poedb is a read-only third-party reference. Its Foulborn page lists, for each unique, the modifier its Foulborn (穢生)
variant replaces and the MutatedUnique* row that replaces it (the hover link names the stat block). The generated C#
file is committed so the Gateway does not need the site at runtime.

Usage (repository root):

    python scripts/re/foulborn_map.py [--refresh]

Pages are cached in artifacts/foulborn-page.html and artifacts/hover/<hash>.html, so a rerun only fetches what is
missing; --refresh drops the cache first. A unique with several listed variants keeps them in page order and the game
uses the first one.

Matching, per listed row, from the hover text (stat display names, value ranges, modifier Family):
  1. every matched stat name must be on the candidate row (all Stat1..8, not just Stat1);
  2. value pairs (min—max) the hover shows must all be the row's stat ranges;
  3. the Family must be one of the row's families;
  4. the base class token (Body, Helmet, Amulet, Jewel, ...) must match; the game data spells Amulet as "Amluet" in
     several MutatedUnique ids, so both spellings count.

The unique's base type comes from the committed UniqueItemSeed.cs, which is itself generated by
scripts/re/unique_items.py.
"""
import argparse
import gzip
import json
import pathlib
import re
import shutil
import time
import urllib.request

ROOT = pathlib.Path(".")
PAGE = "https://poedb.tw/tw/Foulborn"
HOVER = "https://cdn.poedb.tw/cache1/tw/Poe_Data_Mods_hover/"
CACHE = ROOT / "artifacts"
OUTPUT = ROOT / "src/GameServer.Gateway/Item/FoulbornMap.cs"
SEED = ROOT / "src/GameServer.Gateway/Item/UniqueItemSeed.cs"
HEADERS = {"User-Agent": "Mozilla/5.0 (LocalExile data extraction)"}


def fetch(url: str, path: pathlib.Path) -> str:
    if path.exists():
        return path.read_text(encoding="utf-8", errors="replace")
    path.parent.mkdir(parents=True, exist_ok=True)
    request = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(request, timeout=60) as response:
        body = response.read()
    try:
        text = gzip.decompress(body).decode("utf-8", "replace")
    except OSError:
        text = body.decode("utf-8", "replace")
    path.write_text(text, encoding="utf-8")
    return text


def plain(html: str) -> str:
    return " " + re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", html)) + " "


def rows():
    """(unique name, hover hash) for every Foulborn row, from the page's own row markup."""
    html = fetch(PAGE, CACHE / "foulborn-page.html")
    result = []
    for row in re.findall(r'<div class="col"><div class="d-flex border-top rounded">[\s\S]*?</div></div></div>', html):
        name = re.search(r'<span class="UniqueItems UniqueItem">([^<]+)</span>', row)
        if not name:
            slug = re.search(r'class="UniqueItems UniqueItem"[^>]*href="([^"]+)"', row)
            if not slug:
                continue
            name = slug.group(1).replace("_", " ")
        else:
            name = name.group(1)
        hover = re.search(r'<span class="mutatedMod">[\s\S]*?</span>\s*<i data-hover="[^"]*Poe_Data_Mods_hover/([a-f0-9]+)"', row)
        if hover:
            result.append((name, hover.group(1)))
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true", help="drop the cached pages first")
    args = parser.parse_args()
    if args.refresh and CACHE.exists():
        shutil.rmtree(CACHE / "hover", ignore_errors=True)
        (CACHE / "foulborn-page.html").unlink(missing_ok=True)

    stats_list = json.loads((ROOT / "data/tables/Stats.json").read_text(encoding="utf-8"))
    stats = {row["Id"] for row in stats_list}
    mods = json.loads((ROOT / "data/tables/Mods.json").read_text(encoding="utf-8"))
    families = json.loads((ROOT / "data/tables/ModFamily.json").read_text(encoding="utf-8"))
    mutated = [m for m in mods if m["Id"].startswith("MutatedUnique")]
    row_stats = {}
    row_values = {}
    row_families = {}
    for mod in mutated:
        ids, values = set(), []
        for index in range(1, 9):
            stat = mod.get(f"StatsKey{index}")
            if isinstance(stat, int) and 0 <= stat < len(stats_list):
                stat_id = stats_list[stat]["Id"]
                ids.add(stat_id)
                values.append((mod[f"Stat{index}Min"], mod[f"Stat{index}Max"]))
        row_stats[mod["Id"]] = ids
        row_values[mod["Id"]] = values
        row_families[mod["Id"]] = {families[key]["Id"] for key in mod.get("Families", []) if key < len(families)}

    phrases = sorted(((stat.replace("_", " "), stat) for stat in stats), key=lambda pair: -len(pair[0]))
    bases = {name: base for name, base in re.findall(r'new\("([^"]+)",\s*"([^"]+)"', SEED.read_text(encoding="utf-8"))}
    kinds = {"Amulets": "Amulet", "Rings": "Ring", "Belts": "Belt", "BodyArmours": "Body", "Helmets": "Helmet",
             "Boots": "Boots", "Gloves": "Gloves", "Shields": "Shield", "Jewels": "Jewel"}
    tokens = {"Amulet": ["Amulet", "Amluet"], "Ring": ["Ring"], "Belt": ["Belt"], "Body": ["Body"],
              "Helmet": ["Helmet"], "Boots": ["Boots"], "Gloves": ["Gloves"], "Shield": ["Shield"], "Jewel": ["Jewel"]}

    by_unique = {}
    for name, hash_ in rows():
        text = plain(fetch(HOVER + hash_, CACHE / "hover" / f"{hash_}.html"))
        matched = [stat for phrase, stat in phrases if f" {phrase} " in text]
        candidates = [m["Id"] for m in mutated if all(stat in row_stats[m["Id"]] for stat in matched)]
        if not candidates and matched:
            candidates = [m["Id"] for m in mutated if matched[0] in row_stats[m["Id"]]]
        found = {(int(a), int(b)) for a, b in re.findall(r"(\d+)\s*—\s*(\d+)", text)}
        if len(candidates) > 1 and found:
            narrowed = [m for m in candidates if all((lo, hi) in found for lo, hi in row_values[m])]
            candidates = narrowed or candidates
        family = re.search(r"Family\s+([A-Za-z0-9_]+)", text)
        if family and len(candidates) > 1:
            narrowed = [m for m in candidates if family.group(1) in row_families[m]]
            candidates = narrowed or candidates
        parts = (bases.get(name) or "").split("/")
        kind = kinds.get(parts[-2]) if len(parts) >= 2 else None
        if kind and candidates:
            narrowed = [m for m in candidates if any(token in m for token in tokens[kind])]
            candidates = narrowed or candidates
        if candidates:
            kept = by_unique.setdefault(name, [])
            for candidate in candidates:
                if candidate not in kept:
                    kept.append(candidate)
        else:
            print(f"unmatched: {name}")

    lines = [
        "// Generated from poedb.tw/tw/Foulborn (3.29.3b) by scripts/re/foulborn_map.py: a unique's Foulborn (穢生)",
        "// variant replaces its rightmost explicit Mods.dat modifier with the FIRST of these MutatedUnique* rows;",
        "// later ones are alternative variants. Keys ignore punctuation (poedb slugs drop apostrophes).",
        "static class FoulbornMap",
        "{",
        "    static readonly Dictionary<string, string[]> ByKey = new(StringComparer.Ordinal)",
        "    {",
    ]
    for name in sorted(by_unique):
        ids = ", ".join(f'"{modifier}"' for modifier in by_unique[name])
        lines.append(f'        [Key("{name.replace(chr(34), "")}")] = [{ids}],')
    lines += [
        "    };",
        "",
        "    static string Key(string name) => string.Concat(name.Where(char.IsLetterOrDigit)).ToLowerInvariant();",
        "",
        "    /// <summary>The unique's Foulborn modifiers in page order, or null when it has no mapped variant.</summary>",
        "    public static string[]? For(string uniqueName) => ByKey.GetValueOrDefault(Key(uniqueName));",
        "}",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(by_unique)} uniques written to {OUTPUT}")


if __name__ == "__main__":
    main()
